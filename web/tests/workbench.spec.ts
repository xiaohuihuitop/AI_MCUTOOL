import { test, expect } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('../..', import.meta.url))

test('网页、共享MCP和记录器完整闭环', async ({ page, browser }, testInfo) => {
  const errors: string[] = []
  page.on('pageerror', error=>errors.push(error.message))
  const connectionResult = execFileSync(resolve(root,'.venv/Scripts/python.exe'),[resolve(root,'tests/mcp_e2e.py'),resolve(process.env.MCUTOOL_E2E_DIR!,'runtime'),'--connection-check'],{cwd:root,encoding:'utf8',timeout:20000})
  expect(JSON.parse(connectionResult.trim()).attach_then_select).toBe(true)
  await page.goto('/')
  await expect(page.getByText('测试环境 · 当前数据来自显式测试设备，不代表实物测量。')).toBeVisible()
  await expect(page.getByRole('button',{name:'执行按键',exact:true})).toBeDisabled()
  await expect(page.locator('.reading-number').first()).toContainText('—')
  await page.getByRole('button',{name:'Wi-Fi',exact:true}).click()
  await page.getByLabel('设备地址',{exact:true}).fill('http://127.0.0.1:28767')
  await page.getByLabel('访问令牌',{exact:true}).fill('fixture')
  await page.getByRole('button',{name:'连接工具',exact:true}).click()
  await page.getByRole('button',{name:'申请操作权',exact:true}).click()
  await page.getByRole('button',{name:'真实电池',exact:true}).click()
  await expect(page.locator('.notice')).toContainText('供电选择：已完成')
  await page.getByRole('switch',{name:'充电器通路'}).click()
  await expect(page.getByRole('switch',{name:'充电器通路'})).toHaveAttribute('aria-checked','true')
  await expect(page.getByRole('button',{name:'外部电源',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'关闭',exact:true})).toBeDisabled()
  await page.getByRole('switch',{name:'充电器通路'}).click()
  await expect(page.getByRole('switch',{name:'充电器通路'})).toHaveAttribute('aria-checked','false')
  await page.getByLabel('按下 / ms',{exact:true}).fill('3000')
  await page.getByRole('button',{name:'执行按键',exact:true}).click()
  await page.getByRole('button',{name:'取消',exact:true}).click()
  await expect(page.locator('.notice')).toContainText('取消按键：已完成')
  await expect(page.locator('.key-cap.pressed')).toHaveCount(0)
  await expect(page.locator('.reading-number').first()).toContainText('3.900')
  await expect(page.getByText('INA226：电流读数步进 0.125mA，电池电压步进 1.25mV。步进不代表精度，小电流与零点需校准、实测。')).toBeVisible()

  const observerContext = await browser.newContext()
  const observer = await observerContext.newPage()
  await observer.goto('http://127.0.0.1:28766')
  await expect(observer.locator('.reading-number').first()).toContainText('3.900')
  await expect(observer.getByRole('button',{name:'真实电池',exact:true})).toBeDisabled()
  await observerContext.close()

  await page.getByRole('button',{name:'串口与记录',exact:true}).click()
  await page.getByRole('button',{name:'开始记录',exact:true}).click()
  await expect(page.getByRole('button',{name:'停止并保存',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'启用发送',exact:true}).click()
  await expect(page.locator('.notice')).toContainText('串口发送开关：已完成')
  await page.getByLabel('串口发送内容',{exact:true}).fill('MCU测试\n')
  await page.getByRole('button',{name:'发送',exact:true}).click()
  await expect(page.getByLabel('串口接收内容',{exact:true})).toContainText('MCU测试')
  const mcpResult = execFileSync(resolve(root,'.venv/Scripts/python.exe'),[resolve(root,'tests/mcp_e2e.py'),resolve(process.env.MCUTOOL_E2E_DIR!,'runtime')],{cwd:root,encoding:'utf8',timeout:20000})
  expect(JSON.parse(mcpResult.trim()).detach_kept_recording).toBe(true)
  await expect(page.getByRole('button',{name:'停止并保存',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'停止并保存',exact:true}).click()
  await expect(page.getByRole('button',{name:'开始记录',exact:true})).toBeVisible()
  await page.locator('.record-item').first().locator('summary').click()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button',{name:'串口.bin',exact:true}).first().click()
  const downloaded = await downloadPromise
  await downloaded.saveAs(testInfo.outputPath('串口.bin'))
  await page.getByRole('button',{name:'禁用发送',exact:true}).click()
  await expect(page.locator('.notice')).toContainText('串口发送开关：已完成')

  await page.getByRole('button',{name:'设备设置',exact:true}).click()
  await page.getByLabel('参考条件',{exact:true}).fill('仅测试夹具：验证校准提交，不是实物校准')
  await page.getByRole('button',{name:'保存此通道校准',exact:true}).click()
  await expect(page.locator('.notice')).toContainText('保存校准：已完成')
  await page.getByRole('button',{name:'刷新设备设置',exact:true}).click()
  await expect(page.locator('.cal-summary')).toContainText('电池接口电压：有校准记录')
  await page.getByRole('button',{name:'操作面板',exact:true}).click()
  await page.screenshot({path:testInfo.outputPath('工作台-桌面.png'),fullPage:true})
  await page.setViewportSize({width:390,height:844})
  expect(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({path:testInfo.outputPath('工作台-窄屏.png'),fullPage:true})
  await page.getByRole('button',{name:'释放操作权',exact:true}).click()
  await expect(page.getByRole('button',{name:'申请操作权',exact:true})).toBeVisible()
  expect(errors).toEqual([])
})
